-- 1) 학생 명렬 테이블
create table if not exists students (
  id uuid primary key default gen_random_uuid(),
  grade integer not null,       -- 1,2,3학년
  class_no integer not null,    -- 반 번호
  number integer not null,      -- 번호
  name text not null,           -- 이름
  gender text                   -- 남 / 여
);

-- 2) 학생별 종목 배정 테이블 (학생이름 클릭 -> 종목 클릭 -> 여기 저장됨)
create table if not exists event_assignments (
  id uuid primary key default gen_random_uuid(),
  event_id uuid references events(id) on delete cascade,
  student_id uuid references students(id) on delete cascade,
  created_at timestamptz default now(),
  unique (event_id, student_id)   -- 같은 학생이 같은 종목에 중복 배정되지 않도록
);

-- 3) 실시간 기능 켜기 (배정하면 다른 선생님 화면에도 바로 반영되도록)
alter publication supabase_realtime add table event_assignments;

-- 4) 보안 설정: 누구나 조회 가능, 배정도 누구나 가능하게 열어둡니다.
--    (화면 자체는 교사 암호로 잠겨 있는 구조는 다른 탭과 동일합니다)
alter table students enable row level security;
alter table event_assignments enable row level security;

create policy "누구나 학생 명렬 조회 가능" on students for select using (true);
create policy "누구나 배정 조회 가능" on event_assignments for select using (true);
create policy "누구나 배정 추가 가능" on event_assignments for insert with check (true);
create policy "누구나 배정 삭제 가능" on event_assignments for delete using (true);


